pub(crate) fn punctuation(raw: &str, arabic: bool) -> &str {
    match (raw, arabic) {
        (",", true) => "،",
        ("،", false) => ",",
        (";", true) => "؛",
        ("؛", false) => ";",
        ("?", true) => "؟",
        ("؟", false) => "?",
        ("-", true) => "ـ",
        ("ـ", false) => "-",
        _ => raw,
    }
}
